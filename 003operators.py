#OPERATORS >>> Operators are symbols or keywords that perform operations on values and variables.

# Arithmetic Operator
a=10
b=20
print(a+b)
print(a-b)
print(a*b)
print(a/b) #if both numbers are integers it will give us a float
print(10//3) #Floor Division >>> removes the decimal portion
print(10%3) #Modulus >>> gives us remainder
print(10 ** 2) #exponentiation

#Assignment Operators
a = 10 #assigns a value to the operator
a += 10 #adds and assigns value to the operator
a -= 10 #subs and assigns value to the operator
a *= 10
a /= 10

#comparison operators
a = 10
b = 5
print(a == b) #equal to operator
print(a != b) #notEqualTo operator
print(a > b) #greater than operator
print(a < b) #less than operator
print (a >= b) #greater than or equal to
print (a <= b) #less than or equal to

#Logical Operators (and, or, not)

a = 10
print(a>5 and a<20) # and will print true when both coniditions must be true
print(a>5 or a<0) # and will print true when atleast one conidition must be true
print(not True) #reverses a boolean value


